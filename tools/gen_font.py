"""Generate the 8x8 ASCII font ROM used by wall_hud.v and a preview sheet.

The RTL and the Python preview must use the SAME glyphs, so both read the
generated Verilog ROM (or the JSON sidecar produced here).

Run:  python wall/tools/gen_font.py
"""
from __future__ import annotations

import json
from pathlib import Path

from PIL import Image, ImageDraw, ImageFont

CHARS = " 0123456789ABCDEFGHIJKLMNOPQRSTUVWXYZ-./:"
ROOT = Path(__file__).resolve().parents[1]
OUT_V = ROOT / "rtl" / "wall_font_rom.v"
OUT_JSON = ROOT / "tools" / "font.json"
OUT_PNG = ROOT / "docs" / "font_preview.png"

FONT_CANDIDATES = [
    ("C:/Windows/Fonts/lucon.ttf", 11),
    ("C:/Windows/Fonts/consola.ttf", 11),
    ("C:/Windows/Fonts/cour.ttf", 12),
]


def load_font():
    for path, size in FONT_CANDIDATES:
        if Path(path).exists():
            return ImageFont.truetype(path, size), path, size
    raise SystemExit("no usable monospace font found")


def render_glyph(font, ch: str) -> list[int]:
    """Render one char into 8 rows x 8 cols, MSB = leftmost pixel."""
    img = Image.new("L", (8, 8), 0)
    d = ImageDraw.Draw(img)
    # draw with a small offset; the chosen fonts are ~11px so we clamp to the cell
    d.text((0, -2), ch, fill=255, font=font)
    rows = []
    for y in range(8):
        bits = 0
        for x in range(8):
            if img.getpixel((x, y)) >= 110:
                bits |= 1 << (7 - x)
        rows.append(bits)
    return rows


def main() -> None:
    font, path, size = load_font()
    glyphs = {ch: render_glyph(font, ch) for ch in CHARS}

    # preview sheet: one row of chars at 4x
    scale = 4
    sheet = Image.new("RGB", (len(CHARS) * 8 * scale, 8 * scale + 20), (16, 20, 28))
    px = sheet.load()
    for i, ch in enumerate(CHARS):
        for y, bits in enumerate(glyphs[ch]):
            for x in range(8):
                if bits & (1 << (7 - x)):
                    for dy in range(scale):
                        for dx in range(scale):
                            px[i * 8 * scale + x * scale + dx, y * scale + dy] = (230, 240, 255)
    sheet.save(OUT_PNG)

    lines = [
        "// GENERATED by wall/tools/gen_font.py -- do not edit by hand.",
        f"// font: {path} size {size}",
        "// 8x8 glyphs, row 0 first, bit 7 = leftmost pixel.",
        "",
        "module wall_font_rom (",
        "    input  wire [5:0] ch,     // index into CHARS",
        "    input  wire [2:0] row,    // 0..7",
        "    output reg  [7:0] bits",
        ");",
        f"    // CHARS = \"{CHARS}\"",
        "    always @(*) begin",
        "        bits = 8'h00;",
        "        case (ch)",
    ]
    for i, ch in enumerate(CHARS):
        rows = glyphs[ch]
        vals = ", ".join(f"8'h{b:02X}" for b in rows)
        lines.append(f"            6'd{i}: case (row)  // '{ch}'" if ch != " " else f"            6'd{i}: case (row)  // space")
        for r, b in enumerate(rows):
            lines.append(f"                3'd{r}: bits = 8'h{b:02X};")
        lines.append("                default: bits = 8'h00;")
        lines.append("            endcase")
    lines += [
        "            default: bits = 8'h00;",
        "        endcase",
        "    end",
        "endmodule",
        "",
    ]
    OUT_V.write_text("\n".join(lines), encoding="ascii")
    OUT_JSON.write_text(json.dumps({"chars": CHARS, "glyphs": glyphs}), encoding="ascii")
    print(f"wrote {OUT_V} ({len(CHARS)} glyphs)")
    print(f"wrote {OUT_PNG}")


if __name__ == "__main__":
    main()
