import sys
from pathlib import Path
from PIL import Image
W, H, SCALE = 96, 72, 3
ROOT = Path(__file__).resolve().parents[1]
MEDIA = ROOT / "media"
def rgb444(px):
    r, g, b = px[:3]
    return ((r >> 4) << 8) | ((g >> 4) << 4) | (b >> 4)
names = sys.argv[1:] or ["CAM1", "CAM2", "CAM3", "CAM4"]
words, imgs = [], []
for nm in names:
    im = Image.open(MEDIA / (nm + ".BMP")).convert("RGB").resize((W, H), Image.LANCZOS)
    imgs.append(im)
    words += [rgb444(im.getpixel((x, y))) for y in range(H) for x in range(W)]
out = []
out.append("// Generated by tools/make_img_rom.py -- do not edit.")
out.append("// %d banks of %dx%d RGB444 stills, synchronous read, one BRAM." % (len(names), W, H))
out.append("// index = bank*%d + (cy/3)*%d + (cx/3), bank = window id" % (W*H, W))
out.append("`timescale 1ns/1ps")
out.append("")
out.append("module wall_img_rom (")
out.append("    input  wire        clk,")
out.append("    input  wire [14:0] addr,")
out.append("    output reg  [11:0] dout")
out.append(");")
out.append("    reg [11:0] mem [0:%d];" % (len(words) - 1))
out.append("    initial begin")
for i, w in enumerate(words):
    out.append("        mem[%d] = 12'h%03X;" % (i, w))
out.append("    end")
out.append("    always @(posedge clk) dout <= mem[addr];")
out.append("endmodule")
(ROOT / "rtl" / "wall_img_rom.v").write_text("\n".join(out) + "\n", encoding="utf-8")
sheet = Image.new("RGB", (W*SCALE*2 + 8, H*SCALE*2 + 8))
for i, im in enumerate(imgs):
    sheet.paste(im.resize((W*SCALE, H*SCALE), Image.NEAREST), ((i % 2)*(W*SCALE+8), (i // 2)*(H*SCALE+8)))
sheet.save(ROOT / "docs" / "img_rom_preview.png")
print("wrote rom: %d words, %d banks" % (len(words), len(names)))
