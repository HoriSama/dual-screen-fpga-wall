"""Generate the 16x16 CJK font ROM for wall_marquee.v + a preview PNG.

The scrolling marquee at the bottom of the wall needs real Chinese glyphs; the
existing 8x8 ROM (wall_font_rom.v) is ASCII only, and 8x8 Chinese is not
readable.  This script renders the handful of characters the marquee actually
uses from SimHei (the classic 16x16-friendly sans) and emits

    rtl/wall_font_cn.v        combinational 16x16 ROM, one case per glyph
    docs/font_cn_preview.png  the whole line at 3x, for eyeballing

Keep the character order in sync with MARQUEE_STR in wall_marquee.v: the RTL
stores glyph INDICES, so re-running this script with a different text means
re-editing that localparam too (both are printed below to make that easy).

Run:  python wall/tools/gen_font_cn.py
"""
from __future__ import annotations

from pathlib import Path

from PIL import Image, ImageDraw, ImageFont

# The marquee text, exactly as it will scroll (a trailing gap is added by the
# RTL, not here).
TEXT = "因设备调试问题，今日博物馆暂停营业，"

ROOT = Path(__file__).resolve().parents[1]
OUT_V = ROOT / "rtl" / "wall_font_cn.v"
OUT_PNG = ROOT / "docs" / "font_cn_preview.png"

FONT_CANDIDATES = [
    ("C:/Windows/Fonts/simhei.ttf", 16),     # designed for 16x16 bitmaps
    ("C:/Windows/Fonts/msyh.ttc", 16),
    ("C:/Windows/Fonts/simsun.ttc", 16),
]
THRESH = 110          # 0..255 gray -> pixel on
CELL = 16


def load_font():
    for path, size in FONT_CANDIDATES:
        if Path(path).exists():
            return ImageFont.truetype(path, size), path
    raise SystemExit("no CJK font found")


def glyph(font, ch: str) -> list[int]:
    """One 16x16 glyph as 16 rows of 16 bits (bit 15 = leftmost pixel)."""
    img = Image.new("L", (CELL, CELL), 0)
    d = ImageDraw.Draw(img)
    # Anchor the glyph so full-width characters sit on the 16x16 grid: draw at
    # (0, -1) then trim nothing -- SimHei at 16 px already fills the cell.
    d.text((0, -1), ch, font=font, fill=255)
    px = img.load()
    rows = []
    for y in range(CELL):
        w = 0
        for x in range(CELL):
            if px[x, y] >= THRESH:
                w |= 1 << (CELL - 1 - x)
        rows.append(w)
    return rows


def main():
    font, path = load_font()
    # unique glyphs, in order of first appearance
    order: list[str] = []
    for ch in TEXT:
        if ch not in order:
            order.append(ch)
    glyphs = {ch: glyph(font, ch) for ch in order}
    index = {ch: i for i, ch in enumerate(order)}

    # ---------------- RTL ROM ----------------
    lines = [
        "//=============================================================================",
        "// wall_font_cn.v -- 16x16 CJK glyphs for the bottom scrolling marquee",
        "//",
        "// GENERATED by wall/tools/gen_font_cn.py -- do not edit by hand.",
        f"// font: {path}  threshold {THRESH}  cell {CELL}x{CELL}",
        "// Row 0 is the TOP row; bit 15 is the LEFTMOST pixel.",
        "//",
        "// glyph index order (must match MARQUEE_STR in wall_marquee.v):",
        "//   " + " ".join(f"{i}:U+{ord(c):04X}" for i, c in enumerate(order)),
        "//=============================================================================",
        "`timescale 1ns/1ps",
        "",
        "module wall_font_cn (",
        "    input  wire [4:0]  ch,     // glyph index",
        "    input  wire [3:0]  row,    // 0..15, top to bottom",
        "    output reg  [15:0] bits    // bit 15 = leftmost pixel",
        ");",
        f"    localparam integer NGLYPH = {len(order)};",
        "    always @(*) begin",
        "        bits = 16'h0000;",
        "        case (ch)",
    ]
    for i, ch in enumerate(order):
        rows = glyphs[ch]
        lines.append(f"            5'd{i}: case (row)  // U+{ord(ch):04X}")
        for r, w in enumerate(rows):
            lines.append(f"                4'd{r}: bits = 16'h{w:04X};")
        lines.append("                default: bits = 16'h0000;")
        lines.append("            endcase")
    lines += [
        "            default: bits = 16'h0000;",
        "        endcase",
        "    end",
        "endmodule",
        "",
    ]
    OUT_V.write_text("\n".join(lines), encoding="ascii")

    # ---------------- preview ----------------
    unit = TEXT + " " * 14           # 32 characters = one 512 px period
    W, H = len(unit) * CELL, CELL
    img = Image.new("L", (W, H), 0)
    for k, ch in enumerate(unit):
        if ch == " ":
            continue
        for y in range(CELL):
            w = glyphs[ch][y]
            for x in range(CELL):
                if w & (1 << (CELL - 1 - x)):
                    img.putpixel((k * CELL + x, y), 255)
    scale = 3
    big = img.resize((W * scale, H * scale + 2 * scale), Image.NEAREST)
    # draw a 2px guide line where the seam (world x = 640) falls
    canvas = Image.new("L", (big.width, big.height), 40)
    canvas.paste(big, (0, 0))
    d = ImageDraw.Draw(canvas)
    seam = 640 * scale
    d.line([(seam, 0), (seam, canvas.height)], fill=90)
    canvas.save(OUT_PNG)

    print(f"font  : {path}")
    print(f"glyphs: {len(order)}  -> {OUT_V.relative_to(ROOT)}")
    print("  " + "".join(order))
    print(f"string: len={len(TEXT)} (period uses {len(unit)} chars = {len(unit) * CELL} px)")
    idx = [index[ch] for ch in TEXT]
    print("index list: " + ", ".join(f"5'd{i}" for i in idx))
    print(f"preview -> {OUT_PNG.relative_to(ROOT)}")
    # legibility self-check: every glyph must have some ink
    empty = [c for c in order if c != " " and sum(bin(r).count("1") for r in glyphs[c]) < 8]
    if empty:
        print("WARNING: glyphs with almost no ink:", empty)


if __name__ == "__main__":
    main()
