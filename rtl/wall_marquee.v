//=============================================================================
// wall_marquee.v -- bottom scrolling notice board (CJK, 16x16 glyphs)
//
// A dark strip along the bottom 28 lines of the world carries one line of
// Chinese text that scrolls right-to-left at 1 px per frame (60 px/s), i.e.
// one 16 px glyph every 0.27 s.
//
// WHY IT IS PHASE-DRIVEN AND NOT FREE-RUNNING: the strip spans the whole
// 1280-px world, so its left half is drawn by node A and its right half by node
// B.  If the two nodes' scroll positions differ by even one pixel, a glyph is
// torn exactly at the seam -- the same failure the window table avoids by
// broadcasting one table.  So the scroll position is a 9-bit `phase` that both
// nodes take from the SAME counter (A: frame_cnt[8:0]; B: the low byte that
// arrives every frame in the STATE frame plus the one carried in a spare bit).
//
// The period is therefore exactly 512 px = 32 glyph cells, and the string is
// laid out to tile that period (18 glyphs + 14 blanks), so the wrap is
// invisible and no modulo is needed: (x - phase) mod 512 is just a 9-bit
// subtract, and the character index is its top 5 bits.
//
// The glyph ROM is combinational (see wall_font_cn.v, generated by
// tools/gen_font_cn.py).  Its address changes once per 16 pixels, so only the
// final 16:1 bit select sits in the per-pixel path.
//=============================================================================
`timescale 1ns/1ps

module wall_marquee (
    input  wire [10:0] x,        // world x, 0..1279
    input  wire [8:0]  y,        // line, 0..479
    input  wire        en,       // operator turned the marquee on
    input  wire [8:0]  phase,    // scroll position, identical on both nodes
    output wire        hit,      // this pixel belongs to the strip
    output wire [23:0] rgb
);
    // ---- geometry ---------------------------------------------------------
    localparam [8:0] BAND_Y0 = 9'd452;   // strip occupies y = 452..479 (28 px)
    localparam [8:0] TEXT_Y0 = 9'd456;   // glyphs occupy y = 456..471 (16 px)
    localparam integer NCYCLE = 32;      // 32 glyph cells = 512 px

    localparam [23:0] C_BAND = 24'h101820;   // strip background
    localparam [23:0] C_TEXT = 24'hFFD24A;   // amber, like a real notice board

    // ---- scroll position, modulo 512 (no modulo logic: 9-bit subtract) ----
    wire [8:0] rel = x[8:0] - phase;
    wire [4:0] cidx = rel[8:4];          // which of the 32 cells
    wire [3:0] col  = rel[3:0];          // which pixel inside the cell

    // ---- the string: 18 glyphs + 14 blanks = one 512-px period ------------
    // Glyph indices come from wall_font_cn.v (see the order comment there);
    // 5'd17 is past the end of the ROM, so it renders as a blank cell.
    reg [4:0] gch;
    always @(*) begin
        case (cidx)
            5'd0:    gch = 5'd0;    // yin
            5'd1:    gch = 5'd1;    // she
            5'd2:    gch = 5'd2;    // bei
            5'd3:    gch = 5'd3;    // tiao
            5'd4:    gch = 5'd4;    // shi
            5'd5:    gch = 5'd5;    // wen
            5'd6:    gch = 5'd6;    // ti
            5'd7:    gch = 5'd7;    // ，
            5'd8:    gch = 5'd8;    // jin
            5'd9:    gch = 5'd9;    // ri
            5'd10:   gch = 5'd10;   // bo
            5'd11:   gch = 5'd11;   // wu
            5'd12:   gch = 5'd12;   // guan
            5'd13:   gch = 5'd13;   // zan
            5'd14:   gch = 5'd14;   // ting
            5'd15:   gch = 5'd15;   // ying
            5'd16:   gch = 5'd16;   // ye
            5'd17:   gch = 5'd7;    // ，
            default: gch = 5'd17;   // blank (out of ROM range -> 0 bits)
        endcase
    end

    wire [8:0] ry = y - TEXT_Y0;
    wire [15:0] gbits;
    wall_font_cn u_font (.ch(gch), .row(ry[3:0]), .bits(gbits));

    // bit 15 of the row is the leftmost pixel
    wire px_on = gbits[15 - col];

    // ---- output -----------------------------------------------------------
    wire band = (y >= BAND_Y0);
    wire text = (y >= TEXT_Y0) && (y < (TEXT_Y0 + 9'd16)) && px_on;

    assign hit = en && band;
    assign rgb = text ? C_TEXT : C_BAND;
endmodule
